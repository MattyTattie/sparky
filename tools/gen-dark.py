#!/usr/bin/env python3
# tools/gen-dark.py — v0.18: builds dark.css from styles.css. Every rule in styles.css that sets
# a colour gets a matching "html.dark ..." rule with the colour moved to the dark palette
# (light surfaces -> dark surfaces, dark text -> light text, light borders -> dark borders;
# brand/status colours kept). Hand-tuned rules from tools/dark-manual.css go last.
# Run after changing styles.css:  python3 tools/gen-dark.py
import re, colorsys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
css = open(os.path.join(ROOT, 'styles.css')).read()
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
SKIP = re.compile(r'sigpad|sigimg|pdfpage|pdfpages|pdfview|pdfbar|pdfbtn|pdfpn|logoprev|\.bottomnav|header\.top|\.brandmark|\.btn\.primary|\.btn\.danger|\.chip\.on|\.chip\.c[123]|\.chip\.fi|\.fab|\.toast|::selection|b\.code|\.switch|\.beta')
COLOR = re.compile(r'#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b')
PROPS = ('background', 'background-color', 'color', 'border', 'border-color', 'border-top', 'border-bottom', 'border-left', 'border-right', 'border-top-color', 'border-bottom-color', 'border-left-color', 'outline', 'box-shadow', 'fill', 'stroke', 'caret-color')

def parse(c):
    c = c.strip()
    if c == 'white': return (1, 1, 1, 1)
    if c.startswith('#'):
        h = c[1:]
        if len(h) in (3, 4): h = ''.join(x * 2 for x in h)
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)); a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
        return (r, g, b, a)
    n = [float(x) for x in re.findall(r'[\d.]+', c)]
    return (n[0] / 255, n[1] / 255, n[2] / 255, n[3] if len(n) > 3 else 1)
def fmt(r, g, b, a):
    r, g, b = (max(0, min(255, round(x * 255))) for x in (r, g, b))
    return f'#{r:02x}{g:02x}{b:02x}' if a >= 0.999 else f'rgba({r},{g},{b},{a:.2f})'
def remap(c, kind):
    r, g, b, a = parse(c)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if kind == 'shadow': return fmt(0, 0, 0, min(0.6, a * 2.5))
    if kind == 'bg':
        if a < 0.999 and l > 0.6: return fmt(*colorsys.hls_to_rgb(h, 0.30, min(s, .5)), a)  # light tints over dark
        if l >= 0.80: nl = 0.115 + (1 - l) * 0.55; return fmt(*colorsys.hls_to_rgb(h, nl, min(s, 0.45) if s > .2 else s * .6), a)
        if l <= 0.25: return fmt(*colorsys.hls_to_rgb(h, 0.88, s * .5), a)
        return c
    if kind == 'border':
        if l >= 0.70: return fmt(*colorsys.hls_to_rgb(h, 0.26 + (1 - l) * 0.3, min(s, .35)), a)
        return c
    if kind == 'text':
        if l <= 0.40: return fmt(*colorsys.hls_to_rgb(h, 0.86 - l * 0.25, min(s, .6)), a)
        if l >= 0.95 and s < 0.1: return c  # white text on coloured buttons stays white
        return c
    return c
def kind_of(p):
    if p in ('background', 'background-color'): return 'bg'
    if p == 'box-shadow': return 'shadow'
    if p.startswith('border') or p == 'outline': return 'border'
    return 'text'
def prefix(sel):
    out = []
    for s in sel.split(','):
        s = s.strip()
        if not s: continue
        if s.startswith(':root') or s == 'html': out.append('html.dark' + s[len(':root') if s.startswith(':root') else 4:])
        elif s.startswith('html '): out.append('html.dark ' + s[5:])
        elif s.startswith('html,') or s.startswith('html:'): out.append('html.dark' + s[4:])
        else: out.append('html.dark ' + s)
    return ', '.join(out)
rules = []
def walk(text, media=None):
    i = 0
    while i < len(text):
        j = text.find('{', i)
        if j < 0: break
        sel = text[i:j].strip()
        if sel.startswith('@media') or sel.startswith('@supports'):
            depth = 1; k = j + 1
            while depth and k < len(text):
                depth += {'{': 1, '}': -1}.get(text[k], 0); k += 1
            if 'prefers-reduced-motion' not in sel: walk(text[j + 1:k - 1], sel)
            i = k; continue
        if sel.startswith('@keyframes'):
            depth = 1; k = j + 1
            while depth and k < len(text): depth += {'{': 1, '}': -1}.get(text[k], 0); k += 1
            i = k; continue
        k = text.find('}', j); body = text[j + 1:k]; i = k + 1
        if SKIP.search(sel) or sel.startswith(':root'): continue
        decls = []
        for d in body.split(';'):
            if ':' not in d: continue
            p, v = d.split(':', 1); p = p.strip().lower(); v = v.strip()
            if p not in PROPS or not COLOR.search(v) or 'var(' in v and not COLOR.search(v.replace('var(', '')): continue
            kd = kind_of(p)
            nv = COLOR.sub(lambda m: remap(m.group(0), 'bg' if (kd == 'bg') else kd), v)
            if nv != v: decls.append(f'{p}: {nv}')
        if decls: rules.append((media, prefix(sel), decls))
walk(css)
out = ['/* dark.css — generated by tools/gen-dark.py from styles.css (v0.18). Do not edit by hand:',
       '   change styles.css or tools/dark-manual.css and run the script again. */']
for media, sel, decls in rules:
    r = f"{sel} {{ {'; '.join(decls)}; }}"
    out.append(f'{media} {{ {r} }}' if media else r)
out.append(open(os.path.join(ROOT, 'tools', 'dark-manual.css')).read())
open(os.path.join(ROOT, 'dark.css'), 'w').write('\n'.join(out) + '\n')
print(len(rules), 'rules')
